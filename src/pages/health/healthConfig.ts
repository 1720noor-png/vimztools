export const HEALTH_NEW_TOOLS: Tool[] = Object.values(allHealthToolConfigs).map((cfg) => {
  const words = cfg.title
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, ' ')
    .split(/\s+/)
    .filter(Boolean)
  const keywords = Array.from(new Set(['health', 'health tool', ...words, cfg.sub.toLowerCase()])).slice(0, 10)
  return {
    id: cfg.id,
    name: cfg.title,
    categoryId: HEALTH_CATEGORY,
    category: 'Health',
    description: cfg.description,
    keywords,
    path: `/tools/health/${cfg.id}`,
    icon: 'HeartPulse',
    subcategory: cfg.sub,
  }
})

export function findHealthSubcategory(subId: string): HealthSubcategory | undefined {
  return healthSubcategories.find((s) => s.id === subId)
}

