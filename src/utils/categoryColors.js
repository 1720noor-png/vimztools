/**
 * Returns the exact color tokens for any category slug.
 */
export function getCategoryTheme(slug) {
  if (!slug) return FALLBACK_PALETTE
  if (CATEGORY_PALETTE[slug]) return CATEGORY_PALETTE[slug]

  // Soft hashing for unmapped categories to guarantee stable pastels
  const hash = String(slug).split('').reduce((acc, char) => acc + char.charCodeAt(0), 0)
  const options = [
    { bg: '#EAE3FF', border: '#D8CDFC', text: '#2E1E6B', iconBg: '#D4C5FC', accent: '#6C4CF1' },
    { bg: '#DFF6F0', border: '#BEECE0', text: '#0B4A3C', iconBg: '#C5EFE5', accent: '#0D9B79' },
    { bg: '#DFECFF', border: '#C4DCFF', text: '#15396B', iconBg: '#C9E2FF', accent: '#2563EB' },
    { bg: '#FFE8F0', border: '#FFD0E0', text: '#6E1A39', iconBg: '#FFD6E5', accent: '#D92562' },
    { bg: '#FFF2CC', border: '#FFE499', text: '#614B00', iconBg: '#FFE9A6', accent: '#CA8A04' },
    { bg: '#E4F3FF', border: '#CCE5FF', text: '#0A4269', iconBg: '#D0EBFF', accent: '#0284C7' },
    { bg: '#FFE8D6', border: '#FFD2B3', text: '#6E380D', iconBg: '#FFD8BD', accent: '#D97706' },
    { bg: '#DDF5F2', border: '#BEEBE5', text: '#0E4C44', iconBg: '#C8EFEA', accent: '#0D9B79' },
    { bg: '#E8ECF8', border: '#D0D7F0', text: '#222E54', iconBg: '#D8E0F5', accent: '#4F65A8' },
    { bg: '#E3F7E8', border: '#C4EFCF', text: '#114720', iconBg: '#D0F2D9', accent: '#16A34A' },
  ]

  return options[hash % options.length]
}
